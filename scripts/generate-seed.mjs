// Generates supabase/seed.sql from the TypeScript sample data so the database and the
// browser bundle always carry the same versioned reference data.
// Usage: npm run db:seed-sql   (needs Node 22.6+ for --experimental-strip-types)
import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const json = execFileSync(
  process.execPath,
  [
    '--experimental-strip-types',
    '--no-warnings',
    '--input-type=module',
    '-e',
    `import { DATA_SOURCES } from './src/data/sources.ts';
     import { INGREDIENTS } from './src/data/ingredients.ts';
     import { RECIPES } from './src/data/recipes.ts';
     import { CATALOGUE } from './src/data/catalogue.ts';
     console.log(JSON.stringify({ DATA_SOURCES, INGREDIENTS, RECIPES, CATALOGUE }));`,
  ],
  { encoding: 'utf8' },
);
const { DATA_SOURCES, INGREDIENTS, RECIPES, CATALOGUE } = JSON.parse(json);

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const js = (o) => `${q(JSON.stringify(o))}::jsonb`;

const out = ['-- GENERATED by scripts/generate-seed.mjs. Do not edit by hand.', '-- All rows are SAMPLE / SIMULATED reference data.', 'begin;', 'truncate public.catalogue_products, public.recipe_ingredients, public.recipes, public.foods, public.data_sources cascade;'];
for (const s of DATA_SOURCES)
  out.push(`insert into public.data_sources values (${[s.id, s.title, s.publisher, s.version, s.url, s.license, s.attribution, s.permissionStatus, s.isSample, s.notes].map(q).join(',')});`);
for (const f of INGREDIENTS)
  out.push(
    `insert into public.foods values (${q(f.id)},${q(f.name)},${q(f.foodGroup)},${q(f.unitBasis)},${q(f.gramsPerPiece ?? null)},${q(f.state)},${q(f.dietClass)},${arr(f.allergens)},${js(f.nutrientsPer100)},${q(f.sourceId)},${q(f.confidence)},${q(f.verified)});`,
  );
for (const r of RECIPES) {
  out.push(`insert into public.recipes values (${q(r.id)},${r.version},${q(r.name)},${q(r.cuisine)},${arr(r.slots)},${r.servingGrams},${r.prepMinutes},${js(r.steps)},${q(r.sourceId)},${q(r.confidence)});`);
  for (const ri of r.ingredients) out.push(`insert into public.recipe_ingredients values (${q(r.id)},${q(ri.ingredientId)},${ri.amount},${ri.optional},${q(ri.retentionFactor)});`);
}
for (const p of CATALOGUE)
  out.push(
    `insert into public.catalogue_products values (${[p.id, p.provider, p.externalProductId, p.ingredientId, p.brand, p.title, p.packQty, p.packUnit, p.priceInr, p.tier, p.available].map(q).join(',')},${arr(p.allergens)},${q(p.lastCheckedAt)},true);`,
  );
out.push('commit;', '');
writeFileSync('supabase/seed.sql', out.join('\n'));
console.log(`seed.sql: ${DATA_SOURCES.length} sources, ${INGREDIENTS.length} foods, ${RECIPES.length} recipes, ${CATALOGUE.length} products`);
