// Copies the intake system prompt into api/_intake-prompt.js so the Vercel function
// (plain JavaScript, no access to src/) uses exactly the prompt the evaluation tests.
// Run: npm run sync:api. A unit test fails if the two drift apart.
import { writeFileSync } from 'node:fs';
import { LLM_PROMPT_VERSION, SYSTEM_PROMPT } from '../src/domain/intake/llm.ts';

const body = `// GENERATED by scripts/sync-api-prompt.ts from src/domain/intake/llm.ts. Do not edit by hand.
export const PROMPT_VERSION = ${JSON.stringify(LLM_PROMPT_VERSION)};
export const SYSTEM_PROMPT = ${JSON.stringify(SYSTEM_PROMPT)};
`;
writeFileSync('api/_intake-prompt.js', body);
console.log(`Wrote api/_intake-prompt.js (${LLM_PROMPT_VERSION})`);
